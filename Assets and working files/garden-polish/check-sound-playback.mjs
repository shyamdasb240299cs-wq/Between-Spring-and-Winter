import assert from 'node:assert/strict';
import {pausePlayback,startPlayback} from '../../Website/app/sound-playback.ts';
const pending=[];let pauses=0;const errors=[];
const owner={disposed:false,muted:false,error:message=>errors.push(message)};
const layer={started:false,starting:false,failed:false,attempt:0,media:{play(){return new Promise((resolve,reject)=>pending.push({resolve,reject}));},pause(){pauses++;}}};
const flush=async()=>{await Promise.resolve();await Promise.resolve();};
startPlayback(owner,layer,()=>false);
assert.equal(layer.starting,true);
startPlayback(owner,layer,()=>false);
assert.equal(pending.length,1,'A pending playback must not start twice');
pausePlayback(layer);startPlayback(owner,layer,()=>false);
pending[0].reject(new DOMException('Paused by the user','AbortError'));await flush();
assert.equal(layer.starting,true,'The old aborted promise cannot cancel the new on click');
assert.equal(layer.failed,false);
pending[1].resolve();await flush();assert.equal(layer.started,true);assert.equal(layer.starting,false);
pausePlayback(layer);startPlayback(owner,layer,()=>false);
pausePlayback(layer);pending[2].resolve();await flush();
assert.equal(layer.started,false,'A late resolution cannot undo a hidden-tab pause');
startPlayback(owner,layer,()=>false);pending[3].reject(new DOMException('Blocked','NotAllowedError'));await flush();
assert.equal(layer.failed,true);assert.equal(errors.length,1);
startPlayback(owner,layer,()=>false);assert.equal(pending.length,4,'A failure waits for a user retry');
layer.failed=false;startPlayback(owner,layer,()=>false);pending[4].resolve();await flush();
assert.equal(layer.started,true);assert.ok(pauses>=3);
console.log('Rapid music toggles, hidden-tab transitions and failed-play retry guards pass.');
