import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import ts from 'typescript';
import * as THREE from 'three';
const source=await fs.readFile(new URL('../app/printed-pages.ts',import.meta.url),'utf8');
const three=new URL('../node_modules/three/build/three.module.js',import.meta.url).href;
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2020}}).outputText.replace('from "three"',`from "${three}"`);
const {PrintedPages}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const flush=()=>new Promise(resolve=>setImmediate(resolve));
const pending=[],uploaded=[];let loads=0;
const loader={load(src,done,_progress,failed){loads++;pending.push({src,done,failed});return new THREE.Texture();}};
const prints=new PrintedPages(loader,4,()=>{},texture=>uploaded.push(texture));
const page=(src,reverse=false,priority=0)=>({src,reverse,priority});
const a=page('a.webp'),b=page('b.webp',true);
const material=prints.material(b.src,true,THREE.BackSide);
prints.prioritize([a,b]);
let decode,decoded=false;const texture=new THREE.Texture({decode:()=>decoded?Promise.resolve():new Promise(resolve=>{decode=()=>{decoded=true;resolve();};})});
pending.find(p=>p.src==='b.webp').done(texture);await flush();
assert.equal(prints.ready([b]),false,'Load alone must not allow a page turn');
assert.equal(uploaded.length,0,'Do not upload an undecoded image');
decode();await flush();
assert.equal(prints.ready([b]),true);assert.equal(uploaded[0],texture);
assert.equal(material.map,texture);assert.equal(texture.repeat.x,-1);assert.equal(texture.offset.x,1);
prints.prioritize([b]);
pending.find(p=>p.src==='a.webp').done(new THREE.Texture({decode:async()=>{}}));await flush();
assert.equal(prints.ready([a]),false,'Late, unwanted loads must not become ready');
prints.prioritize([page('c.webp')]);
assert.equal(prints.ready([b]),false,'Evicted maps cannot be exposed');
const before=loads;prints.prioritize([b]);await flush();
assert.equal(loads,before,'Backtracking reuses the decoded page without another request');
assert.equal(prints.ready([b]),true);
prints.dispose();
const pool=[],parallel=new PrintedPages({load(src,done){pool.push({src,done});return new THREE.Texture();}},1,()=>{});
const chapter=Array.from({length:20},(_,i)=>page(`page-${i}.webp`,false,i));
parallel.prioritize(chapter);assert.equal(pool.length,4,'Bound concurrent page decode/upload work');
pool[0].done(new THREE.Texture({decode:async()=>{}}));await flush();assert.equal(pool.length,5);
parallel.dispose();pool[1].done(new THREE.Texture({decode:async()=>{}}));await flush();
assert.equal(pool.length,5,'Disposal stops the loading queue');
let finishLoad,finishUpload;
const scheduled=new PrintedPages({load(_src,done){finishLoad=done;return new THREE.Texture();}},1,()=>{},()=>new Promise(resolve=>{finishUpload=resolve;}));
scheduled.prioritize([a]);finishLoad(new THREE.Texture({decode:async()=>{}}));await flush();
assert.equal(scheduled.ready([a]),false,'Decoded pages stay hidden until scheduled GPU upload completes');
finishUpload();await flush();assert.equal(scheduled.ready([a]),true);scheduled.dispose();
let failLoad;
const broken=new PrintedPages({load(_src,done){failLoad=done;return new THREE.Texture();}},1,()=>{});
broken.prioritize([a]);failLoad(new THREE.Texture({decode:async()=>{throw Error('Corrupt image');}}));await flush();
assert.equal(broken.ready([a]),false,'A decode failure cannot expose a blank page');broken.dispose();
// Simultaneous front/back conversions must both be released on unmount,
// including the bitmap replaced in the per-source backtracking cache.
const bitmapLoads=[],bitmaps=[];
globalThis.ImageBitmap=class{closed=0;close(){this.closed++;}};
globalThis.createImageBitmap=async()=>{const bitmap=new ImageBitmap();bitmaps.push(bitmap);return bitmap;};
const duplicate=new PrintedPages({load(_src,done){bitmapLoads.push(done);return new THREE.Texture();}},1,()=>{});
duplicate.prioritize([page('blank.webp'),page('blank.webp',true)]);
for(const done of bitmapLoads)done(new THREE.Texture({decode:async()=>{}}));
await flush();assert.equal(bitmaps.length,2);duplicate.dispose();
assert.ok(bitmaps.every(bitmap=>bitmap.closed===1),'Release every concurrent bitmap exactly once');
delete globalThis.createImageBitmap;delete globalThis.ImageBitmap;
console.log('Printed pages passed: decode and GPU upload before exposure, reverse-side orientation, stale loads, cached backtracking, bounded concurrency and disposal.');
